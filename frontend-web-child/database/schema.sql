-- PostgreSQL schema for the child care tracking application.
-- Safe to re-run: objects are created only when absent.

BEGIN;

CREATE TABLE IF NOT EXISTS caregivers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  address TEXT,
  phone TEXT,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS children (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  nickname TEXT,
  date_of_birth DATE NOT NULL,
  gender TEXT NOT NULL CHECK (gender IN ('Laki-laki', 'Perempuan')),
  entry_date DATE NOT NULL,
  health_status TEXT NOT NULL DEFAULT 'Normal'
    CHECK (health_status IN ('Normal', 'Perlu Perhatian')),
  condition TEXT NOT NULL DEFAULT 'Normal'
    CHECK (condition IN ('Normal', 'Disabilitas')),
  caregiver_id BIGINT REFERENCES caregivers(id) ON DELETE SET NULL,
  background TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (entry_date >= date_of_birth)
);

CREATE TABLE IF NOT EXISTS child_allergies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  child_id BIGINT NOT NULL REFERENCES children(id) ON DELETE CASCADE,
  description TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (child_id, description)
);

CREATE TABLE IF NOT EXISTS child_special_conditions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  child_id BIGINT NOT NULL REFERENCES children(id) ON DELETE CASCADE,
  description TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (child_id, description)
);

CREATE TABLE IF NOT EXISTS health_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  child_id BIGINT NOT NULL REFERENCES children(id) ON DELETE CASCADE,
  recorded_at DATE NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('Normal', 'Perlu Perhatian')),
  title TEXT NOT NULL,
  summary TEXT NOT NULL,
  notes TEXT,
  recorded_by TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS growth_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  child_id BIGINT NOT NULL REFERENCES children(id) ON DELETE CASCADE,
  recorded_at DATE NOT NULL,
  weight_kg NUMERIC(5,2) NOT NULL CHECK (weight_kg > 0),
  height_cm NUMERIC(5,2) NOT NULL CHECK (height_cm > 0),
  notes TEXT,
  recorded_by TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (child_id, recorded_at)
);

CREATE TABLE IF NOT EXISTS growth_assessments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  child_id BIGINT NOT NULL REFERENCES children(id) ON DELETE CASCADE,
  assessed_at DATE NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('Normal', 'Perlu Perhatian')),
  summary TEXT NOT NULL,
  disclaimer TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (child_id, assessed_at)
);

CREATE TABLE IF NOT EXISTS growth_assessment_indicators (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id BIGINT NOT NULL REFERENCES growth_assessments(id) ON DELETE CASCADE,
  indicator_type TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('Normal', 'Perlu Perhatian')),
  value NUMERIC(7,2) NOT NULL,
  unit TEXT NOT NULL,
  interpretation TEXT NOT NULL,
  UNIQUE (assessment_id, indicator_type)
);

CREATE TABLE IF NOT EXISTS daily_notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  child_id BIGINT NOT NULL REFERENCES children(id) ON DELETE CASCADE,
  recorded_at DATE NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('Aktivitas', 'Makan', 'Tidur', 'Perilaku', 'Kesehatan', 'Lainnya')),
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  recorded_by TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS reminders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  child_id BIGINT REFERENCES children(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  description TEXT,
  type TEXT NOT NULL CHECK (type IN ('Penting', 'Rutin')),
  due_date DATE NOT NULL,
  due_time TIME,
  repeat_rule TEXT NOT NULL DEFAULT 'Tidak berulang'
    CHECK (repeat_rule IN ('Tidak berulang', 'Setiap hari', 'Setiap minggu', 'Setiap bulan')),
  completed BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS need_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  section TEXT,
  detail TEXT,
  quantity BIGINT NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  unit TEXT,
  gender TEXT,
  size TEXT,
  color TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_children_name ON children (name);
CREATE INDEX IF NOT EXISTS idx_health_records_child_date ON health_records (child_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_growth_records_child_date ON growth_records (child_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_growth_assessments_child_date ON growth_assessments (child_id, assessed_at DESC);
CREATE INDEX IF NOT EXISTS idx_daily_notes_child_date ON daily_notes (child_id, recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_reminders_due_open ON reminders (due_date, due_time) WHERE completed = FALSE;
CREATE INDEX IF NOT EXISTS idx_reminders_child ON reminders (child_id);
CREATE INDEX IF NOT EXISTS idx_need_items_category ON need_items (category);
CREATE UNIQUE INDEX IF NOT EXISTS uq_need_items_name_ci ON need_items (LOWER(BTRIM(name)));

COMMIT;
